"""Puertos: lo que la capa de aplicación necesita del mundo exterior, sin saber cómo se hace.

La infraestructura (Firestore, Anthropic, cifrado) los implementa; las pruebas usan
versiones en memoria. Así los casos de uso no dependen de Firebase.
"""

from __future__ import annotations

from datetime import datetime
from typing import Iterable, Protocol

from dominio.consumo import EventoConsumo


class NoAutorizado(Exception):
    """La persona no tiene permiso para esto."""


class NoEncontrado(Exception):
    """No existe lo que se pidió."""


class DatosInvalidos(Exception):
    """Los datos no sirven para calcular o guardar."""


class RepoOrganizaciones(Protocol):
    def crear(self, datos: dict) -> str: ...
    def leer(self, org: str) -> dict | None: ...
    def actualizar(self, org: str, cambios: dict) -> None: ...
    def ids(self) -> Iterable[str]: ...
    # invitaciones por correo (antes de que la persona entre por primera vez)
    def invitaciones_de(self, email: str) -> dict[str, str]: ...
    def guardar_invitacion(self, email: str, org: str, rol: str | None) -> None: ...
    # tokens de ingesta: solo se guarda la huella, nunca el token
    def guardar_token(self, huella: str, datos: dict) -> None: ...
    def leer_token(self, huella: str) -> dict | None: ...
    def tokens_de(self, org: str) -> list[dict]: ...
    def revocar_token(self, huella: str) -> None: ...
    # secretos de la empresa (clave de administración de Anthropic), ya cifrados
    def guardar_secreto(self, org: str, nombre: str, cifrado: str | None) -> None: ...
    def leer_secreto(self, org: str, nombre: str) -> str | None: ...


class RepoPlanes(Protocol):
    def leer_caso(self, org: str) -> dict | None: ...
    def guardar_caso(self, org: str, caso: dict) -> None: ...
    def leer_seguimiento(self, org: str) -> dict | None: ...
    def guardar_seguimiento(self, org: str, seg: dict) -> None: ...
    def leer_plan(self, org: str) -> dict | None: ...
    def guardar_plan(self, org: str, doc: dict) -> None: ...
    def agregar_historial(self, org: str, entrada: dict) -> None: ...


class RepoConsumo(Protocol):
    def registrar(self, org: str, mes: str, filas: list[tuple[EventoConsumo, str, str]]) -> list[str]:
        """Suma cada evento (evento, clave de persona, día) una sola vez. Devuelve las claves tocadas."""
        ...
    def gasto_de(self, org: str, mes: str) -> dict[str, dict]: ...
    def crear_alerta(self, org: str, id_: str, datos: dict) -> bool: ...
    def guardar_gasto_api(self, org: str, mes: str, datos: dict) -> None: ...


class Reloj(Protocol):
    def ahora(self) -> datetime: ...


class Cifrador(Protocol):
    def cifrar(self, texto: str) -> str: ...
    def descifrar(self, cifrado: str) -> str: ...


class FuenteCostosAnthropic(Protocol):
    def costo_por_actor(self, clave_admin: str, desde: datetime, hasta: datetime) -> dict:
        """{'filas': [{'email','usuario','modelo','usd'}], 'datos_hasta': iso | None}"""
        ...
